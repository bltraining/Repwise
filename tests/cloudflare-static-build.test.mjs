import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile, readdir, stat } from 'node:fs/promises'
import worker from '../cloudflare/worker.js'

test('Cloudflare preview includes the original Repwise app and its essential pages without the internal name', async () => {
  const root = new URL('../dist-cloudflare/', import.meta.url)
  const files = await readdir(root)
  for (const file of ['index.html', 'app.js', 'runtime-config.js', 'preview-mode.js', 'founder-access.js', 'sw.js', 'manifest.webmanifest', 'cgv.html', 'confidentialite.html', 'mentions-legales.html', '_headers']) {
    await stat(new URL(file, root))
  }
  assert.ok(files.includes('icons'))
  const html = await readFile(new URL('index.html', root), 'utf8')
  const app = await readFile(new URL('app.js', root), 'utf8')
  const runtime = await readFile(new URL('runtime-config.js', root), 'utf8')
  const preview = await readFile(new URL('preview-mode.js', root), 'utf8')
  const founderAccess = await readFile(new URL('founder-access.js', root), 'utf8')
  const headers = await readFile(new URL('_headers', root), 'utf8')
  const sw = await readFile(new URL('sw.js', root), 'utf8')
  assert.match(html, /data-v="c"[^>]*>Entraînement/)
  assert.match(html, /data-v="h"[^>]*>Historique/)
  assert.match(html, /data-v="n"[^>]*>Nutrition/)
  assert.match(html, /data-v="k"[^>]*>Coach/)
  assert.doesNotMatch(html, /Cassandre|Assistant Repwise|repwiseAssistant/i)
  assert.doesNotMatch(html, /Commercial|Clients|Programmes|Technique|Financier/)
  assert.match(html, /id="whChart"/)
  assert.doesNotMatch(html, /vendor\/supabase|runtimeConfigFailure/)
  assert.match(app, /function loadProg\(\)/)
  assert.match(app, /SB=null,LIVE=false/)
  assert.doesNotMatch(app, /createClient|cassandre|repwiseAssistant/i)
  assert.doesNotMatch(runtime, /fetch\(|supabase\.co|\.netlify\/functions/)
  assert.doesNotMatch([app, runtime, preview, founderAccess].join('\n'), /cassandre|assistant repwise/i)
  assert.match(founderAccess, /api\/founder-panel/)
  assert.match(founderAccess, /api\/repwise-session/)
  assert.match(preview, /MODE APERÇU/)
  assert.match(preview, /\.hy\{min-height:116px\}\.hy \.bt\{width:48px;height:108px\}\.hy \.bt svg\{transform:scale\(1\.18\)/)
  assert.doesNotMatch(preview, /\.hy \.gl svg\{transform/)
  assert.match(app, /Math\.floor\(H\/4\)/)
  assert.match(html, /\.hy\{display:flex/)
  assert.match(html, /flex-wrap:wrap/)
  assert.match(html, /name="viewport" content="width=device-width, initial-scale=1/)
  assert.match(headers, /connect-src 'self'/)
  assert.match(headers, /Strict-Transport-Security: max-age=31536000/)
  assert.doesNotMatch(headers, /supabase\.co|\.netlify|stripe|whatsapp/i)
  const publicHtml = await Promise.all(['cgv.html', 'confidentialite.html', 'mentions-legales.html'].map(file => readFile(new URL(file, root), 'utf8')))
  const manifest = await readFile(new URL('manifest.webmanifest', root), 'utf8')
  const legalCss = await readFile(new URL('legal/legal.css', root), 'utf8')
  const workerSource = await readFile(new URL('../cloudflare/worker.js', import.meta.url), 'utf8')
  const workerConfig = await readFile(new URL('../wrangler.cloudflare.jsonc', import.meta.url), 'utf8')
  assert.match(workerConfig, /"name": "repwise"/)
  assert.doesNotMatch([html, app, runtime, preview, founderAccess, headers, sw, manifest, legalCss, ...publicHtml].join('\n'), /cassandre|assistant repwise/i)
  assert.match(workerSource, /CASSANDRE_OWNER_USER_ID/)
})

test('unmatched paths fail closed without a backend', async () => {
  const response = await worker.fetch(new Request('https://repwise-cassandre.workers.dev/api/cassandre-command'))
  assert.equal(response.status, 404)
  assert.deepEqual(await response.json(), { error: 'not_found' })
  assert.equal(response.headers.get('cache-control'), 'no-store, private')
})
